export function getSortedMaterialsList(): MaterialProperties[] {
  const rank = (cat: MaterialCategory) => {
    const idx = MATERIAL_CATEGORY_ORDER.indexOf(cat);
    return idx >= 0 ? idx : 99;
  };
  return Object.values(MATERIALS).sort((a, b) => {
    const diff = rank(a.category) - rank(b.category);
    if (diff !== 0) return diff;
    return a.name.localeCompare(b.name, 'ru');
  });
}
