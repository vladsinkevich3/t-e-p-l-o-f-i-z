export interface MaterialProperties {
  id: string;
  name: string;
  category: MaterialCategory;
  density: number; // плотность в сухом состоянии ρ₀, кг/м³
  heatCapacity: number; // удельная теплоемкость c₀, кДж/(кг·°С)
  lambda_dry?: number; // теплопроводность в сухом состоянии λ₀, Вт/(м·°С)
  lambda_A: number; // расчетная λ_А, Вт/(м·°С) при условиях эксплуатации А
  lambda_B: number; // расчетная λ_Б, Вт/(м·°С) при условиях эксплуатации Б
  s_A: number; // коэффициент теплоусвоения s_А (период 24 ч), Вт/(м²·°С)
  s_B: number; // коэффициент теплоусвоения s_Б (период 24 ч), Вт/(м²·°С)
  mu: number; // коэффициент паропроницаемости μ, мг/(м·ч·Па)
}

